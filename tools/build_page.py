"""Build index.html (the GitHub Pages site) from tools/page_template.html.

Inlines every docs/<g>_codes.json and every tools/<g>/password.mjs. Each codec module becomes a namespace:
the `export ` keywords are stripped and the code is wrapped as `const SB1 = (() => { ...; return {decode, ...}; })();`.
Also lists docs/img/<g>/*.png (proof shots), docs/img/logos/*.png and patches/*.ips for the page.
A game whose code list is missing or broken is left out. A game with no codec (or a broken one, with a warning)
gets a null namespace and shows its codes without a generator.

    python tools/build_page.py
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAMES = {"sb1": "SB1", "sb2": "SB2", "sb3": "SB3", "sb4": "SB4", "sb5": "SB5", "mega": "MEGA",
         "pce90": "PCE90", "pceub": "PCEUB", "pce93": "PCE93", "pce94": "PCE94", "mega8": "MEGA8",
         "nes1": "NES1", "nes2": "NES2",
         "gb1": "GB1", "gb2": "GB2", "gb3": "GB3", "pocket": "POCKET", "max": "MAX"}
EXPORT = re.compile(r"^export\s+(?:const|let|var|function\*?|class)\s+([A-Za-z_$][\w$]*)", re.M)
NODE = shutil.which("node")


def script_safe(s):
    return s.replace("</", "<\\/")


def namespace(name, src):
    if re.search(r"^\s*import\b|^export\s+(default|\{|\*)", src, re.M):
        raise ValueError("uses import or a non-plain export")
    names = EXPORT.findall(src)
    if not names:
        raise ValueError("no exports found")
    body = re.sub(r"^export\s+", "", src, flags=re.M)
    js = "const %s = (() => {\n%s\nreturn { %s };\n})();" % (name, body.strip(), ", ".join(names))
    if "</script" in js.lower():
        raise ValueError("contains </script")
    if NODE:  # one broken codec would stop the whole page, so make sure it parses and runs
        r = subprocess.run([NODE, "-e", js], capture_output=True, text=True)
        if r.returncode:
            raise ValueError("node: " + (r.stderr.strip().splitlines() or ["error"])[-1])
    return js


def main():
    codecs, codes, shots, missing = [], {}, {}, []
    for g, name in GAMES.items():
        # the code list is required; the codec is optional (a game with no passwords has none)
        try:
            data = json.loads((ROOT / "docs" / (g + "_codes.json")).read_text(encoding="utf-8"))
            if not isinstance(data, list) or not all(isinstance(e, dict) and "code" in e and "effect" in e for e in data):
                raise ValueError("code list is not a list of {code, effect, ...}")
        except (OSError, ValueError) as err:
            print("warning: leaving out %s: %s" % (g, err), file=sys.stderr)
            missing.append(g)
            data = []
        for e in data:
            e.setdefault("versions", [])
            e.setdefault("note", "")
        js = "const %s = null;  // no codec" % name
        mjs = ROOT / "tools" / g / "password.mjs"
        if data and mjs.exists():
            try:
                js = namespace(name, mjs.read_text(encoding="utf-8"))
            except (OSError, ValueError) as err:
                print("warning: %s: codec left out, codes only: %s" % (g, err), file=sys.stderr)
                js = "const %s = null;  // codec left out: %s" % (name, str(err).replace("\n", " "))
        codecs.append(js)
        codes[g] = data
        img = ROOT / "docs" / "img" / g
        shots[g] = sorted(p.name for p in img.glob("*.png")) if img.is_dir() else []
    logos = sorted(p.stem for p in (ROOT / "docs" / "img" / "logos").glob("*.png"))
    patches = sorted(p.name for p in (ROOT / "patches").glob("*.ips"))

    tpl = (ROOT / "tools" / "page_template.html").read_text(encoding="utf-8")
    note = "<!-- generated by tools/build_page.py from tools/page_template.html, docs/*_codes.json and tools/*/password.mjs. Edit those and rerun; don't edit this file. -->"
    data_js = "const CODES = %s;\nconst SHOTS = %s;\nconst LOGOS = %s;\nconst PATCHES = %s;" % (
        script_safe(json.dumps(codes, ensure_ascii=False, separators=(",", ":"))),
        script_safe(json.dumps(shots, separators=(",", ":"))), json.dumps(logos), json.dumps(patches))
    for key, val in (("<!--@GENERATED@-->", note), ("/*@CODECS@*/", "\n\n".join(codecs)), ("/*@DATA@*/", data_js)):
        if tpl.count(key) != 1:
            sys.exit("template must contain %s exactly once" % key)
        tpl = tpl.replace(key, val)
    out = ROOT / "index.html"
    out.write_bytes(tpl.encode("utf-8"))  # bytes, so Windows doesn't turn \n into \r\n
    print("wrote %s (%d KB): %s" % (out.relative_to(ROOT), out.stat().st_size // 1024,
          ", ".join("%s %d codes" % (g, len(codes[g])) for g in GAMES if g not in missing)))
    if missing:
        print("left out: " + ", ".join(missing))


if __name__ == "__main__":
    main()
